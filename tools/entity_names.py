"""Writes HD Toolbox's src-tauri/src/tasks/seed_search/entity_names.rs from
HDDLL's EntityTypeName, which is where SpecsHD's seed_search.csv gets its
names.

usage: python tools/entity_names.py <HD-Toolbox folder>
"""

import pathlib
import re
import sys

HD_CPP = pathlib.Path(__file__).parent / "../3rdparty/HDDLL/src/hd.cpp"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = pathlib.Path(sys.argv[1]) / "src-tauri/src/tasks/seed_search/entity_names.rs"

    source = HD_CPP.read_text(encoding="utf-8")
    body = source[source.index("const char *EntityTypeName("):]
    body = body[: body.index("default:")]
    names = re.findall(r'case (\d+):\s*return "([^"]*)";', body)

    lines = [
        "// Generated by hd-seed-search's tools/entity_names.py from HDDLL's EntityTypeName.",
        "// Don't edit by hand.",
        "",
        "pub fn entity_name(entity_type: u32) -> &'static str {",
        "    match entity_type {",
    ]
    lines += [f'        {n} => "{name}",' for n, name in names]
    lines += ['        _ => "Unknown",', "    }", "}", ""]
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(names)} names to {out.resolve()}")


if __name__ == "__main__":
    main()
